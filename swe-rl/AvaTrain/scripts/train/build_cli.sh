# Abort early (before touching the cluster) if any required env var is empty.
validate_required_env() {
  local var
  local missing=()
  for var in "${REQUIRED_ENV_VARS[@]}"; do
    [[ -z "${!var:-}" ]] && missing+=("${var}")
  done
  if ((${#missing[@]} > 0)); then
    echo "Missing required env vars (no argparse default): ${missing[*]}" >&2
    return 1
  fi
  return 0
}

# Flatten a list of group-array NAMES into one flat list of env var names.
_collect_group_names() {
  local -n _dest=$1
  shift
  local group
  for group in "$@"; do
    local -n _g="$group"
    _dest+=("${_g[@]}")
    unset -n _g
  done
  return 0
}

# Build CLI_ARGS from every registry group, then append the user passthrough last.
build_cli_args() {
  CLI_ARGS=()
  local opt_names=() flag_names=()
  _collect_group_names opt_names  "${ALL_OPTION_GROUPS[@]}"
  _collect_group_names flag_names "${ALL_FLAG_GROUPS[@]}"

  [[ ${#opt_names[@]}  -gt 0 ]] && append_option_vars CLI_ARGS "${opt_names[@]}"
  [[ ${#flag_names[@]} -gt 0 ]] && append_flag_vars   CLI_ARGS "${flag_names[@]}"
  return 0
}

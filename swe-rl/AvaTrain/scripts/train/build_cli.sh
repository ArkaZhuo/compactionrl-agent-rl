#!/bin/bash

append_option_vars() {
  local -n _out=$1
  shift
  local env val flag
  local -a parts
  for env in "$@"; do
    local -n _src="$env"
    val="${_src:-}"
    unset -n _src
    [[ -z "$val" ]] && continue
    flag="--$(printf '%s' "$env" | tr '[:upper:]_' '[:lower:]-')"
    read -r -a parts <<< "$val"
    _out+=("$flag" "${parts[@]}")
  done
  return 0
}

# For each ENV VAR name: append the bare `--flag` iff the var == "1".
append_flag_vars() {
  local -n _out=$1
  shift
  local env flag
  for env in "$@"; do
    local -n _src="$env"
    if [[ "${_src:-}" == "1" ]]; then
      flag="--$(printf '%s' "$env" | tr '[:upper:]_' '[:lower:]-')"
      _out+=("$flag")
    fi
    unset -n _src
  done
  return 0
}

